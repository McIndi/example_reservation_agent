#!/bin/bash
# Run INSIDE the throwaway export instance, as root (copy it in first: `limactl cp export/sanitize-guest.sh
# k8s-export:/tmp/`, then `limactl shell k8s-export -- sudo bash /tmp/sanitize-guest.sh`; export/RECIPIENT.md).
# Makes a pre-init image generic: no Lima agent, no host credentials, fresh machine-id, cloud-init ready to run again
# with the recipient's datasource. Does not touch the installed packages or the pre-pulled images.
set -eux -o pipefail
[ "$(id -u)" = 0 ] || { echo "run with sudo" >&2; exit 1; }
test -e /etc/kubernetes/admin.conf && { echo "this image already has a cluster; export a pre-init image" >&2; exit 1; }

# Lima leftovers
systemctl disable --now lima-guestagent.service 2>/dev/null || true
rm -f /etc/systemd/system/lima-guestagent.service /usr/local/bin/lima-guestagent
umount /mnt/lima-cidata 2>/dev/null || true   # Lima 2.x keeps its cidata ISO mounted there, read-only
rm -rf /etc/systemd/system/lima-*.service.d /mnt/lima-cidata
# The Lima login user keeps its account (it cannot delete itself from inside) but loses every credential.
# KEEP_USER (the Packer boxes set it to `vagrant`) keeps its key and stays unlocked: sshd refuses key logins
# to locked accounts, and that user is how `vagrant up` gets in.
KEEP_USER="${KEEP_USER:-}"
for h in /home/*; do
  u=$(basename "$h"); id "$u" >/dev/null 2>&1 || continue
  [ "$u" = "$KEEP_USER" ] && continue
  rm -f "$h/.ssh/authorized_keys"; passwd -l "$u" || true
done
rm -f /etc/sudoers.d/*lima* /etc/sudoers.d/90-cloud-init-users

# Identity and logs
truncate -s0 /etc/machine-id; rm -f /var/lib/dbus/machine-id
rm -f /etc/ssh/ssh_host_*            # regenerated by sshd-keygen at the recipient's first boot
cloud-init clean --logs --seed
journalctl --rotate && journalctl --vacuum-time=1s
rm -rf /var/log/cloud-init* /var/log/dnf* /root/.bash_history /home/*/.bash_history /home/*/.zsh_history
dnf clean all

# Make the raw disk as sparse as possible, then stop.
fstrim -av || true
sync
echo "sanitized; now on the Mac: limactl stop <clone>"
